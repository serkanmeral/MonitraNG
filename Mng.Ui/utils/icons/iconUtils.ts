import * as TablerIcons from 'vue-tabler-icons';

/**
 * Icon Type Definitions
 */
export type IconType = 'mdi' | 'tabler';

/**
 * Icon Component Type (Vue component)
 */
export type IconComponent = any;

/**
 * Get Tabler Icon Component by name
 * @param iconName - Icon component name (e.g., "ChartPieIcon")
 * @returns Icon component or null if not found
 */
export function getTablerIconComponent(iconName: string): IconComponent | null {
  if (!iconName) return null;

  // Normalize icon name (remove spaces, ensure proper case)
  const normalizedName = iconName.trim();
  
  // Try exact match first
  if (TablerIcons[normalizedName] && typeof TablerIcons[normalizedName] === 'object') {
    return TablerIcons[normalizedName];
  }

  // Try with "Icon" suffix if not already present
  if (!normalizedName.endsWith('Icon')) {
    const nameWithIcon = `${normalizedName}Icon`;
    if (TablerIcons[nameWithIcon] && typeof TablerIcons[nameWithIcon] === 'object') {
      return TablerIcons[nameWithIcon];
    }
  }

  // Try case-insensitive match
  const lowerName = normalizedName.toLowerCase();
  for (const key in TablerIcons) {
    if (key.toLowerCase() === lowerName || key.toLowerCase() === `${lowerName}icon`) {
      if (typeof TablerIcons[key] === 'object') {
        return TablerIcons[key];
      }
    }
  }

  return null;
}

/**
 * Get MDI Icon class name
 * @param iconName - MDI icon name (e.g., "home", "mdi-home")
 * @returns MDI class name (e.g., "mdi mdi-home")
 */
export function getMdiIconClass(iconName: string): string {
  if (!iconName) return '';

  // Normalize icon name
  let normalizedName = iconName.trim();

  // Remove "mdi-" prefix if present
  if (normalizedName.startsWith('mdi-')) {
    normalizedName = normalizedName.substring(4);
  }

  // Remove "mdi " prefix if present
  if (normalizedName.startsWith('mdi ')) {
    normalizedName = normalizedName.substring(4);
  }

  // Return MDI class format
  return `mdi mdi-${normalizedName}`;
}

/**
 * Get Icon Component based on type
 * @param iconName - Icon name
 * @param iconType - Icon type ('mdi' or 'tabler')
 * @returns Icon component (for Tabler) or class name string (for MDI), or null
 */
export function getIcon(iconName: string | undefined | null, iconType: IconType = 'tabler'): IconComponent | string | null {
  if (!iconName) return null;

  if (iconType === 'mdi') {
    return getMdiIconClass(iconName);
  } else {
    // Tabler (default)
    return getTablerIconComponent(iconName);
  }
}

/**
 * List all available Tabler icons (for Icon Picker)
 * @returns Array of icon names
 */
export function getTablerIconList(): string[] {
  return Object.keys(TablerIcons)
    .filter(key => key.endsWith('Icon') && typeof TablerIcons[key] === 'object')
    .sort();
}

